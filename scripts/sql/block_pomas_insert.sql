-- HQ (KSS) PARTS9 — refuse new purchase orders from the old PO screen.
--
-- STATUS: install on KSS only. SYP POMAS is the HQ→SYP transfer book; do not
-- install this there.
--
-- The old purchase-order screen inserts dbo.POMAS and dbo.PODET. HQ PO
-- never writes those tables. This rejects the insert and rolls the save back,
-- including an ICLOW stamp made in the same transaction.
--
-- Updates still work, so an existing PO can be billed or received.
--
-- Turn the block off only for a one-off that must be typed in the old screen:
--   DISABLE TRIGGER dbo.trg_POMAS_block_insert ON dbo.POMAS;
--   DISABLE TRIGGER dbo.trg_PODET_block_insert ON dbo.PODET;
-- Turn it back on:
--   ENABLE TRIGGER dbo.trg_POMAS_block_insert ON dbo.POMAS;
--   ENABLE TRIGGER dbo.trg_PODET_block_insert ON dbo.PODET;

USE PARTS9;
GO

